const { app, BrowserWindow } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')

const output = path.resolve(process.env.MOUSSE_BROWSER_VIEWER_EVIDENCE || path.join(__dirname, '..', '.mousse-dev', 'browser-viewer-evidence'))
app.setPath('userData', path.join(output, 'electron-user-data'))
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
const timeout = setTimeout(() => { console.error('Browser viewer fixture timed out'); app.exit(1) }, 90_000)
timeout.unref()

async function main() {
  await app.whenReady()
  await fs.mkdir(output, { recursive: true })
  const win = new BrowserWindow({
    width: 1440, height: 960, useContentSize: true, show: false,
    webPreferences: { offscreen: true, contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false, partition: 'browser-viewer-visual-fixture' }
  })
  const errors = []
  win.webContents.on('did-finish-load', () => console.log('DID_FINISH_LOAD'))
  win.webContents.on('did-fail-load', (_event, code, description, url) => console.error('DID_FAIL_LOAD', code, description, url))
  win.webContents.on('console-message', (event) => { if (event.level === 'error') { errors.push(event.message); console.error(event.message) } })
  if (!process.env.MOUSSE_BROWSER_VIEWER_FIXTURE_URL) throw new Error('Run through scripts/run-browser-viewer-visual-check.mjs')
  console.log('LOAD ' + process.env.MOUSSE_BROWSER_VIEWER_FIXTURE_URL)
  await win.loadURL(process.env.MOUSSE_BROWSER_VIEWER_FIXTURE_URL)
  console.log('LOADED')
  const js = (source) => win.webContents.executeJavaScript(source)
  const assert = async (source, name) => {
    for (let i = 0; i < 50; i++) { if (await js(source)) { console.log('PASS ' + name); return } await delay(100) }
    throw new Error(name)
  }
  await assert('Boolean(document.querySelector(".browser-automation-viewer"))', 'viewer rendered')
  await assert('document.querySelector(".browser-automation-connection")?.textContent.includes("connected")', 'connected status visible')
  await assert(`Boolean(document.querySelector('img[alt*="Managed browser"]'))`, 'managed screenshot visible')
  await js('document.querySelector("button") && Array.from(document.querySelectorAll("button")).find((button) => button.textContent.includes("Take control"))?.click()')
  await assert(`Boolean(document.querySelector('[aria-label="Human browser controls"]'))`, 'human controls rendered after takeover')
  await assert('Array.from(document.querySelectorAll("button")).some((button) => button.textContent.includes("Resume agent"))', 'resume control rendered')
  await js('document.querySelector(".browser-automation-screenshot img")?.click()')
  await assert('document.body.innerText.includes("Human click action applied")', 'human pointer action reaches history')
  await js(`(() => { const input = document.querySelector('[aria-label="Human navigation URL"]'); const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set; setter.call(input, 'http://fixture.local/after-human'); input.dispatchEvent(new Event('input', { bubbles: true })); Array.from(document.querySelectorAll('button')).find((button) => button.textContent === 'Go')?.click(); })()`)
  await assert('document.querySelector(".browser-automation-url")?.textContent.includes("after-human")', 'human navigation updates URL')
  await js(`(() => { const input = document.querySelector('[aria-label="Human browser key"]'); const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set; setter.call(input, 'Tab'); input.dispatchEvent(new Event('input', { bubbles: true })); Array.from(document.querySelectorAll('button')).find((button) => button.textContent === 'Send key')?.click(); })()`)
  await assert('document.body.innerText.includes("Human key action applied")', 'human key action reaches history')
  await js('window.fixtureViewer.disconnect()')
  await assert('document.querySelector(".browser-automation-connection")?.textContent.includes("disconnected")', 'disconnect state visible')
  await js('Array.from(document.querySelectorAll("button")).find((button) => button.textContent === "Reconnect")?.click()')
  await assert('document.querySelector(".browser-automation-connection")?.textContent.includes("connected")', 'reconnect state visible')
  await js('Array.from(document.querySelectorAll("button")).find((button) => button.textContent.includes("Resume agent"))?.click()')
  await assert('Array.from(document.querySelectorAll("button")).some((button) => button.textContent.includes("Take control"))', 'agent control resumes')
  await assert(`document.body.innerText.includes('fixture-image') === false && Boolean(document.querySelector('[aria-label="Open artifact observation.png"]'))`, 'history shows sanitized artifact metadata')
  await fs.writeFile(path.join(output, 'desktop.png'), (await win.webContents.capturePage()).toPNG())
  win.setContentSize(760, 960)
  await delay(300)
  await assert('document.documentElement.scrollWidth <= window.innerWidth + 8', 'narrow viewer has no extreme overflow')
  await fs.writeFile(path.join(output, 'narrow.png'), (await win.webContents.capturePage()).toPNG())
  win.setContentSize(900, 700)
  await delay(300)
  await js('document.documentElement.style.zoom = "1.25"')
  await delay(300)
  await assert('document.querySelector(".browser-automation-screenshot img")?.getBoundingClientRect().width > 0', 'high-DPI screenshot remains visible')
  await fs.writeFile(path.join(output, 'hidpi.png'), (await win.webContents.capturePage()).toPNG())
  if (errors.length) throw new Error('Renderer errors: ' + errors.join('; '))
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: true, errors, at: new Date().toISOString() }, null, 2))
  win.destroy(); clearTimeout(timeout); app.exit(0)
}

main().catch(async (error) => {
  console.error(error)
  await fs.mkdir(output, { recursive: true })
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: false, error: String(error), at: new Date().toISOString() }, null, 2))
  clearTimeout(timeout); app.exit(1)
})
