const { app, BrowserWindow, webContents } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const output = path.resolve(__dirname, '..', '.mousse-dev', 'browser-lifetime-evidence', crypto.randomUUID())
app.setPath('userData', path.join(output, 'electron-user-data'))
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
const timeout = setTimeout(() => { console.error('Browser lifetime fixture timed out'); app.exit(1) }, 90_000)
timeout.unref()
const checks = []
const errors = []
let win
async function main() {
  await fs.mkdir(output, { recursive: true })
  await app.whenReady()
  win = new BrowserWindow({ show: false, width: 1200, height: 800, useContentSize: true,
    webPreferences: { webviewTag: true, contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  win.webContents.on('console-message', (event) => { if (event.level === 'error') { errors.push(event.message); console.error(event.message) } })
  const js = (source) => win.webContents.executeJavaScript(source)
  const waitFor = async (test, name) => {
    for (let i = 0; i < 100; i++) {
      if (await test()) { checks.push(name); console.log('PASS ' + name); return }
      await delay(50)
    }
    throw new Error(name)
  }
  if (!process.env.MOUSSE_BROWSER_LIFETIME_URL) throw new Error('Use run-browser-lifetime-check.mjs')
  await win.loadURL(process.env.MOUSSE_BROWSER_LIFETIME_URL)
  await waitFor(() => js('Boolean(window.lifetimeFixture) && document.querySelectorAll("webview").length === 2'), 'actual BrowserPanel mounts both guests')
  const ids = await js('({first: lifetimeFixture.first, second: lifetimeFixture.second})')
  const guestId = (id) => js(`document.querySelector('webview[data-browser-tab-id="${id}"]')?.getWebContentsId()`)
  const firstId = await guestId(ids.first)
  const guest = webContents.fromId(firstId)
  await waitFor(() => guest.executeJavaScript('Boolean(window.documentToken && document.querySelector("#draft"))'), 'owned page loaded')
  await guest.executeJavaScript('document.querySelector("#draft").value="unsaved draft";document.cookie="lifetime=kept; path=/"')
  const webviewRect = await js(`(() => { const r=document.querySelector('webview[data-browser-tab-id="${ids.first}"]').getBoundingClientRect(); return {x:r.x,y:r.y} })()`)
  const guestTargets = await guest.executeJavaScript(`(() => { const rect = (selector) => { const r=document.querySelector(selector).getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2} }; return {count:rect('#count'),draft:rect('#draft')} })()`)
  const hostPoint = (target) => ({ x: Math.round(webviewRect.x + target.x), y: Math.round(webviewRect.y + target.y) })
  const click = (point) => {
    win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
    win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
  }
  const countPoint = hostPoint(guestTargets.count)
  assert.equal(await js(`document.elementFromPoint(${countPoint.x},${countPoint.y})?.closest('.browser-panel') !== null`), true)
  checks.push('visible guest point is a positive renderer hit target'); console.log('PASS visible guest point is a positive renderer hit target')
  guest.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...guestTargets.count })
  guest.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...guestTargets.count })
  await waitFor(() => guest.executeJavaScript('window.clicks === 1'), 'guest-native mouse input reaches owned control at derived coordinates')
  guest.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...guestTargets.draft })
  guest.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...guestTargets.draft })
  guest.sendInputEvent({ type: 'char', keyCode: 'Z' })
  await waitFor(() => guest.executeJavaScript('document.querySelector("#draft").value.includes("Z")'), 'guest-native keyboard input reaches owned control')
  await guest.executeJavaScript('window.scrollTo(0,300)')
  const snapshot = () => guest.executeJavaScript('({token:window.documentToken, draft:document.querySelector("#draft").value, cookie:document.cookie, x:innerWidth, y:innerHeight, scroll:scrollY, clicks:window.clicks})')
  const baseline = await snapshot()
  assert.ok(baseline.x > 400 && baseline.y > 300 && baseline.scroll === 300)
  const unchanged = async (name) => {
    await delay(150)
    assert.equal(await guestId(ids.first), firstId, name + ': same WebContents')
    assert.deepEqual(await snapshot(), baseline, name + ': same document/form/cookie/viewport/scroll')
    checks.push(name); console.log('PASS ' + name)
  }
  await js(`document.querySelector('[aria-label="Browser menu"]').click()`)
  await waitFor(() => js('Boolean(document.querySelector(".browser-menu-floating"))'), 'overflow portal opened')
  await js('lifetimeFixture.view("files")')
  await unchanged('switching main view retains page and viewport')
  await waitFor(() => js('!document.querySelector(".browser-menu-floating") && Boolean(document.querySelector("webview").closest("[inert]"))'), 'inactive browser closes portal and is inert')
  const hit = await js(`document.elementFromPoint(${countPoint.x},${countPoint.y})?.closest('.browser-panel') === null`)
  assert.equal(hit, true, 'hidden native guest is not a renderer hit target')
  click(countPoint)
  win.webContents.sendInputEvent({ type: 'char', keyCode: 'X' })
  await unchanged('hidden guest is excluded from hit testing and retains state after injected input')
  await js('lifetimeFixture.view("browser")')
  await unchanged('returning to browser preserves unsaved state')
  await js('Array.from(document.querySelectorAll("[role=tab]")).find(b=>b.textContent==="Managed automation").click()')
  await unchanged('managed viewer retains existing human page')
  await js('Array.from(document.querySelectorAll("[role=tab]")).find(b=>b.textContent==="Manual browser").click()')
  await waitFor(() => js(`!document.querySelector('.browser-automation-viewer') && document.querySelector('.browser-manual-surface')?.getAttribute('aria-hidden') === 'false'`), 'manual surface is visible again')
  await js(`document.querySelector('[aria-label="Point and click to select element"]').click()`)
  await waitFor(() => guest.executeJavaScript('Boolean(window.__mousseCancelElementPicker)'), 'real guest element picker starts')
  await js('lifetimeFixture.thread("thread-b")')
  await unchanged('switching threads retains inactive guest viewport')
  await waitFor(() => guest.executeJavaScript('!window.__mousseCancelElementPicker && !document.querySelector("[data-mousse-element-picker]")'), 'thread switch cancels hidden guest picker')
  assert.deepEqual(await js('lifetimeFixture.attachments()'), {})
  await js('lifetimeFixture.thread("thread-empty")')
  await unchanged('thread with no tabs retains background page')
  await js('lifetimeFixture.thread("thread-a");lifetimeFixture.collapse(true)')
  await unchanged('collapsed app panel retains viewport')
  await js('lifetimeFixture.collapse(false)')
  await unchanged('reopened app panel preserves page')
  const layout = await js(`(() => { const surface=document.querySelector('.browser-manual-surface');const viewport=document.querySelector('.browser-viewport.active'); return { manualVisible:surface.getAttribute('aria-hidden')==='false', viewportOpacity:getComputedStyle(viewport).opacity, viewportInert:Boolean(viewport.closest('[inert]')), managedMounted:Boolean(document.querySelector('.browser-automation-viewer')) } })()`)
  assert.deepEqual(layout, { manualVisible: true, viewportOpacity: '1', viewportInert: false, managedMounted: false })
  // Hidden-window compositor capture is diagnostic, not visible-app qualification.
  await fs.writeFile(path.join(output, 'browser-panel.png'), (await win.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG())
  await js('lifetimeFixture.profile()')
  await waitFor(async () => guest.isDestroyed() && (await guestId(ids.first)) !== firstId, 'profile switch destroys old guest despite reused UI tab id')
  const nextGuest = webContents.fromId(await guestId(ids.first))
  await waitFor(() => nextGuest.executeJavaScript('Boolean(window.documentToken)'), 'new profile guest loaded')
  assert.equal(await nextGuest.executeJavaScript('document.cookie'), '')
  assert.equal(await nextGuest.executeJavaScript('document.querySelector("#draft").value'), '')
  checks.push('new profile has separate cookies and page state')
  await js('lifetimeFixture.close(lifetimeFixture.first)')
  await waitFor(() => nextGuest.isDestroyed(), 'explicit close destroys guest')
  assert.deepEqual(errors, [])
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: true, checks, baseline, layout, errors }, null, 2))
  console.log(JSON.stringify({ passed: true, checks: checks.length, output }))
  win.destroy(); clearTimeout(timeout); app.exit(0)
}
main().catch(async (error) => {
  console.error(error)
  await fs.mkdir(output, { recursive: true })
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: false, checks, errors, error: String(error) }, null, 2))
  if (win && !win.isDestroyed()) win.destroy()
  clearTimeout(timeout); app.exit(1)
})
