/** The declared access of `method`, or undefined for a method outside the protocol list (an installation command, a test double). */
export function gitAccessOf(method: string): GitAccess | undefined {
  return Object.hasOwn(GIT_ACCESS, method) ? (GIT_ACCESS as Record<string, GitAccess>)[method] : undefined
}

